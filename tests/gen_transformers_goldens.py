#!/usr/bin/env python3
"""Emit GPU golden vectors from the pinned transformers Inkling 2 modules.

Source: transformers commit eeee11099135592f1d03c2871fbd3d8132e5a4d7
`src/transformers/models/inkling2/modeling_inkling2.py`.

The script execs those classes (decorators stripped) and runs their `forward`
methods. Re-run from the repo root after downloading that file:

    python3 tests/gen_transformers_goldens.py /path/to/modeling_inkling2.py
"""

import json
import sys
from types import SimpleNamespace

import torch
import torch.nn as nn
import torch.nn.functional as F

PIN = "eeee11099135592f1d03c2871fbd3d8132e5a4d7"
RANGES = [
    (133, 194),  # L2 clip family
    (230, 240),  # padding mask
    (243, 283),  # causal conv helpers (decorator lines dropped)
    (286, 351),  # Inkling2ShortConvolution
    (353, 412),  # Inkling2DynamicShortConvolution
    (733, 753),  # softcap and softcapped SwiGLU
]


def load_modules(path: str):
    lines = open(path).read().splitlines()
    chunk = []
    for start, end in RANGES:
        for line in lines[start - 1 : end]:
            if line.lstrip().startswith("@"):
                continue
            chunk.append(line)
    ns = {
        "torch": torch,
        "nn": nn,
        "F": F,
        "math": __import__("math"),
        "Cache": object,
        "Inkling2TextConfig": object,
        "Unpack": dict,
        "TransformersKwargs": dict,
    }
    exec("\n".join(chunk), ns)
    return ns


class DecodeCache:
    """Subset of transformers `LinearAttentionLayer.update_conv_state`."""

    def __init__(self):
        self.conv_states = {}
        self.ready = set()
        self.seen = set()
        self.kernel = {}

    def is_recording_past(self, _layer):
        return False

    def get_conv_state(self, layer, state_idx=0):
        return self.conv_states.get((layer, state_idx))

    def update_conv_state(self, conv_states, layer, state_idx=0, conv_kernel_size=None):
        key = (layer, state_idx)
        if key not in self.ready:
            k = conv_kernel_size if conv_kernel_size is not None else conv_states.shape[-1]
            self.kernel[key] = k
            self.conv_states[key] = torch.zeros(*conv_states.shape[:-1], k)
            self.ready.add(key)
            self.seen.discard(key)
        if key not in self.seen:
            full = conv_states
            self.seen.add(key)
            if full.shape[-1] < self.kernel[key]:
                full = F.pad(full, (self.kernel[key] - full.shape[-1], 0))
        else:
            full = torch.cat([self.conv_states[key], conv_states], dim=-1)
        self.conv_states[key] = full[..., -self.kernel[key] :].clone()
        return full


def f32s(t):
    return [float(v) for v in t.detach().float().reshape(-1).tolist()]


def rust_array(name, values):
    body = ", ".join(f"{v:.8e}" for v in values)
    return f"pub static {name}: [f32; {len(values)}] = [{body}];\n"


def main():
    path = sys.argv[1]
    ns = load_modules(path)
    torch.manual_seed(0)

    soft_x = torch.linspace(-0.3, 0.3, 300)
    soft = {}
    for cap in (25.0, 30.0):
        y = ns["Inkling2Softcap"](cap)(soft_x)
        soft[cap] = f32s(y)

    gate = torch.linspace(-0.4, 1.2, 280)
    up = torch.linspace(-1.0, 0.8, 280)
    cfg = SimpleNamespace(mlp_gate_softcap=4.0, mlp_up_softcap=25.0)
    sw = ns["Inkling2SoftcappedSwiGLU"](cfg)(gate, up)

    heads, dim = 3, 8
    x = torch.randn(1, heads, dim)
    clip = ns["Inkling2LogScaledL2Clip"](
        SimpleNamespace(log_scaling_alpha=0.3, log_scaling_n_floor=4.0),
        heads,
        dim,
        1.5,
    )
    with torch.no_grad():
        clip.scale.copy_(torch.randn_like(clip.scale))
    l2_y = []
    positions = [0, 1, 3, 7, 15]
    for pos in positions:
        y = clip(x, torch.tensor([pos]))
        l2_y.append(f32s(y))

    channels, kernel = 8, 4
    static = ns["Inkling2ShortConvolution"](channels, kernel, 0, 0)
    with torch.no_grad():
        static.conv1d.weight.copy_(torch.randn_like(static.conv1d.weight))
    cache = DecodeCache()
    static_steps = []
    for _ in range(7):
        step_x = torch.randn(1, 1, channels)
        y = static(step_x, cache=cache)
        static_steps.append((f32s(step_x), f32s(y)))

    dyn = ns["Inkling2DynamicShortConvolution"](channels, 5, 2, kernel, 0, 1)
    with torch.no_grad():
        dyn.static_weight.copy_(torch.randn_like(dyn.static_weight))
        dyn.weight_proj.weight.copy_(torch.randn_like(dyn.weight_proj.weight))
    dcache = DecodeCache()
    dyn_steps = []
    for _ in range(7):
        step_x = torch.randn(1, 1, channels)
        dyn_in = torch.randn(1, 1, 5)
        y = dyn(step_x, dyn_in, cache=dcache)
        dyn_steps.append((f32s(step_x), f32s(dyn_in), f32s(y)))

    parts = [
        f"// Generated by tests/gen_transformers_goldens.py from transformers {PIN}.\n",
        "// Do not edit by hand. Outputs are `forward` of the pinned classes.\n",
        rust_array("SOFTCAP_25_X", f32s(soft_x)),
        rust_array("SOFTCAP_25_Y", soft[25.0]),
        rust_array("SOFTCAP_30_Y", soft[30.0]),
        rust_array("SWIGLU_GATE", f32s(gate)),
        rust_array("SWIGLU_UP", f32s(up)),
        rust_array("SWIGLU_Y", f32s(sw)),
        rust_array("L2_X", f32s(x)),
        rust_array("L2_SCALE", f32s(clip.scale)),
        "pub static L2_POSITIONS: [u32; 5] = [0, 1, 3, 7, 15];\n",
    ]
    for i, row in enumerate(l2_y):
        parts.append(rust_array(f"L2_Y_{i}", row))
    parts.append(rust_array("STATIC_WEIGHT", f32s(static.conv1d.weight)))
    for i, (sx, sy) in enumerate(static_steps):
        parts.append(rust_array(f"STATIC_X_{i}", sx))
        parts.append(rust_array(f"STATIC_Y_{i}", sy))
    parts.append(rust_array("DYN_STATIC_WEIGHT", f32s(dyn.static_weight)))
    parts.append(rust_array("DYN_PROJ", f32s(dyn.weight_proj.weight)))
    for i, (sx, sd, sy) in enumerate(dyn_steps):
        parts.append(rust_array(f"DYN_X_{i}", sx))
        parts.append(rust_array(f"DYN_IN_{i}", sd))
        parts.append(rust_array(f"DYN_Y_{i}", sy))
    out = "tests/transformers_goldens.rs"
    open(out, "w").write("".join(parts))
    print("wrote", out, "bytes", sum(len(p) for p in parts))


if __name__ == "__main__":
    main()
