#!/usr/bin/env python3
"""Goldens from one forward of the pinned Inkling2SparseMoeBlock.

    python3 tests/gen_moe_goldens.py /path/to/modeling_inkling2.py
"""

import sys
from types import SimpleNamespace

import torch
import torch.nn as nn
import torch.nn.functional as F

PIN = "eeee11099135592f1d03c2871fbd3d8132e5a4d7"


def load_moe(path: str):
    lines = open(path).read().splitlines()
    chunk = []
    for line in lines[732:831]:
        if line.lstrip().startswith("@"):
            continue
        chunk.append(line)
    ns = {
        "torch": torch,
        "nn": nn,
        "F": F,
        "Inkling2TextConfig": object,
        "Inkling2Config": object,
        "ACT2FN": {"sigmoid": torch.sigmoid},
    }
    exec("\n".join(chunk), ns)
    return ns


def f32s(t):
    return [float(v) for v in t.detach().float().reshape(-1).tolist()]


def rust_array(name, values):
    body = ", ".join(f"{v:.9e}" for v in values)
    return f"pub static {name}: [f32; {len(values)}] = [{body}];\n"


def config(**kwargs):
    base = dict(
        hidden_size=32,
        n_routed_experts=16,
        num_local_experts=16,
        moe_intermediate_size=16,
        num_experts_per_tok=4,
        scoring_func="sigmoid",
        routed_scaling_factor=1.5,
        mlp_gate_softcap=4.0,
        mlp_up_softcap=25.0,
    )
    base.update(kwargs)
    base["num_local_experts"] = base["n_routed_experts"]
    return SimpleNamespace(**base)


def margins(module, tokens):
    with torch.no_grad():
        flat = tokens.reshape(-1, tokens.shape[-1]).float()
        scores = torch.sigmoid(flat @ module.gate.weight.float().T)
        keys = scores + module.gate.e_score_correction_bias.float()
        k = module.gate.top_k
        vals = torch.topk(keys, k + 1, dim=-1).values
        return vals[:, k - 1] - vals[:, k]


def widen_margins(module, tokens, floor=1.5e-4):
    """Push runner-up bias down until every token's top-k gap is at least `floor`."""
    for _ in range(8):
        gap = margins(module, tokens)
        if torch.all(gap >= floor - 1e-8):
            break
        with torch.no_grad():
            flat = tokens.reshape(-1, tokens.shape[-1]).float()
            scores = torch.sigmoid(flat @ module.gate.weight.float().T)
            keys = scores + module.gate.e_score_correction_bias.float()
            k = module.gate.top_k
            idx = torch.topk(keys, k + 1, dim=-1).indices
            for t in range(flat.shape[0]):
                g = float(margins(module, tokens[t : t + 1])[0])
                if g < floor:
                    runner = int(idx[t, k])
                    module.gate.e_score_correction_bias[runner] -= floor - g + 1e-5
    # Pull the closest token's runner-up back up so one margin sits near the floor.
    gap = margins(module, tokens)
    t = int(torch.argmin(gap))
    with torch.no_grad():
        flat = tokens.reshape(-1, tokens.shape[-1]).float()
        scores = torch.sigmoid(flat @ module.gate.weight.float().T)
        keys = scores + module.gate.e_score_correction_bias.float()
        k = module.gate.top_k
        idx = torch.topk(keys, k + 1, dim=-1).indices
        runner = int(idx[t, k])
        current = float(gap[t])
        target = max(floor, 2e-4)
        module.gate.e_score_correction_bias[runner] += current - target
    gap = margins(module, tokens)
    assert torch.all(gap >= 1e-4 - 1e-6), gap
    return gap


def run_case(ns, cfg, tokens):
    module = ns["Inkling2SparseMoeBlock"](cfg)
    with torch.no_grad():
        module.experts.gate_up_proj.normal_(0, 0.15)
        module.experts.down_proj.normal_(0, 0.15)
        module.gate.weight.normal_(0, 0.35)
        module.gate.e_score_correction_bias.normal_(0, 0.05)
    gap = widen_margins(module, tokens)
    y = module(tokens)
    return module, y, gap


def main():
    ns = load_moe(sys.argv[1])
    torch.manual_seed(7)
    cases = [
        ("NEAR", config(), torch.randn(1, 4, 32)),
        (
            "WIDE",
            config(
                hidden_size=24,
                n_routed_experts=128,
                moe_intermediate_size=8,
                num_experts_per_tok=8,
            ),
            torch.randn(1, 2, 24),
        ),
    ]
    parts = [
        f"// Generated by tests/gen_moe_goldens.py from transformers {PIN}.\n",
        "// One forward of Inkling2SparseMoeBlock. Do not edit by hand.\n",
    ]
    for name, cfg, tokens in cases:
        module, y, gap = run_case(ns, cfg, tokens)
        print(name, "min margin", float(gap.min()), "max", float(gap.max()))
        parts.append(rust_array(f"{name}_ROUTER", f32s(module.gate.weight)))
        parts.append(rust_array(f"{name}_BIAS", f32s(module.gate.e_score_correction_bias)))
        parts.append(rust_array(f"{name}_GATE_UP", f32s(module.experts.gate_up_proj)))
        parts.append(rust_array(f"{name}_DOWN", f32s(module.experts.down_proj)))
        parts.append(rust_array(f"{name}_X", f32s(tokens)))
        parts.append(rust_array(f"{name}_Y", f32s(y)))
    open("tests/moe_goldens.rs", "w").write("".join(parts))
    print("wrote tests/moe_goldens.rs")


if __name__ == "__main__":
    main()
